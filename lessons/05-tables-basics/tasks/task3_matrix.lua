-- Матрица — таблица таблиц. Напиши local function transpose(m),
-- которая возвращает НОВУЮ транспонированную матрицу
-- (строки становятся столбцами).
--
-- ПРИМЕР:
--   вход:  { {1, 2, 3}, {4, 5, 6} }       (2 строки x 3 столбца)
--   выход: { {1, 4}, {2, 5}, {3, 6} }     (3 строки x 2 столбца)
--
-- ТРЕБОВАНИЯ:
-- 1. Не меняй исходную матрицу (создай новую!).
-- 2. Работай для любых размеров MxN (не только 2x3).
-- 3. Пустая матрица {} → верни {}.
--
-- НАВОДКИ МЕНТОРА:
--  1) Размеры: строк = #m, столбцов = #m[1]. Но что если m пустая?
--     Копай: проверь #m == 0 первым делом.
--  2) Новая матрица res: res[j][i] = m[i][j]. Но res[j] сначала надо
--     создать как пустую таблицу! Иначе "index nil". Порядок создания?
--  3) Для печати матрицы пригодятся вложенные циклы + table.concat
--     для строки: print(table.concat(row, " ")).
--
-- ПРОВЕРКИ:
local function print_matrix(m)
  for _, row in ipairs(m) do
    print(table.concat(row, " "))
  end
end

